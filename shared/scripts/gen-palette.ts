/**
 * Writes shared/src/ui/palette.css from shared/src/ui/palette.ts and prints the contrast report.
 *   npx tsx shared/scripts/gen-palette.ts
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { ACCENTS, AA_MIN, buildPalette, chartCompanions, contrastChecks, type Ramp } from '../src/ui/palette';

const p = buildPalette();

const block = (ramps: Ramp[]) =>
  ramps
    .map((r) =>
      [
        ...r.steps.map((v, i) => `  --${r.name}-${i + 1}: ${v};`),
        `  --${r.name}-contrast: ${r.contrast};`,
      ].join('\n'),
    )
    .join('\n');

const accentMap = (name: string) => {
  const comp = chartCompanions(name);
  return [
    ...Array.from({ length: 12 }, (_, i) => `  --accent-${i + 1}: var(--${name}-${i + 1});`),
    `  --accent-contrast: var(--${name}-contrast);`,
    `  --chart-1: var(--${name}-9);`,
    ...comp.map((c, i) => `  --chart-${i + 2}: var(--${c}-9);`),
  ].join('\n');
};

const css = `/*
 * GENERATED by shared/scripts/gen-palette.ts from shared/src/ui/palette.ts. Do not edit by hand.
 * 12-step ramps (Radix-style semantics) for gray, the ten app accents and the status hues, light and dark.
 * Text/solid pairs are solved for WCAG AA (see palette.test.ts).
 */

:root {
${block(p.light)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${block(p.dark)
  .split('\n')
  .map((l) => '  ' + l)
  .join('\n')}
  }
}

:root[data-theme='dark'] {
${block(p.dark)}
}

/* Tailwind: bg-gray-3, text-accent-11, border-ember-6, … (our 1–12 steps, not Tailwind's 50–950). */
@theme inline {
${[...p.light.map((r) => r.name), 'accent']
  .map((n) =>
    [
      ...Array.from({ length: 12 }, (_, i) => `  --color-${n}-${i + 1}: var(--${n}-${i + 1});`),
      `  --color-${n}-contrast: var(--${n}-contrast);`,
    ].join('\n'),
  )
  .join('\n')}
}

/* Accent mapping. Set data-accent on <html> (mountApp does) or on any subtree. Indigo is the default. */
:root,
[data-accent='indigo'] {
${accentMap('indigo')}
}
${ACCENTS.filter((a) => a !== 'indigo')
  .map((a) => `\n[data-accent='${a}'] {\n${accentMap(a)}\n}`)
  .join('\n')}
`;

const out = resolve(import.meta.dirname, '../src/ui/palette.css');
writeFileSync(out, css);

const checks = contrastChecks(p);
const failing = checks.filter((c) => c.ratio < AA_MIN);
const min = (pair: string) => Math.min(...checks.filter((c) => c.pair === pair).map((c) => c.ratio));
console.log(`wrote ${out}`);
for (const pair of [...new Set(checks.map((c) => c.pair))]) console.log(`  min ${pair}: ${min(pair)}`);
for (const r of [...p.light, ...p.dark].filter((r, i) => i % 1 === 0)) void r;
if (failing.length) {
  console.log('FAILING:');
  for (const f of failing) console.log(`  ${f.theme} ${f.ramp} ${f.pair}: ${f.ratio}`);
  process.exitCode = 1;
}
console.log('\nsolids (light):', p.light.map((r) => `${r.name} ${r.steps[8]}`).join(', '));
console.log('solids (dark):', p.dark.map((r) => `${r.name} ${r.steps[8]}`).join(', '));
console.log('text-11 (light):', p.light.map((r) => `${r.name} ${r.steps[10]}`).join(', '));
console.log('text-11 (dark):', p.dark.map((r) => `${r.name} ${r.steps[10]}`).join(', '));
